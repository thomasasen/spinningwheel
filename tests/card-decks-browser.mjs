import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';

const browser=await chromium.launch({headless:true});
const context=await browser.newContext({reducedMotion:'reduce',viewport:{width:1240,height:900},acceptDownloads:true});
const page=await context.newPage(),errors=[];
page.on('pageerror',e=>errors.push(e.stack||e.message));
await page.route(/^https?:/,route=>route.abort());
try{
  await page.goto(pathToFileURL(resolve('index.html')).href);
  await page.waitForFunction(()=>Boolean(window.__casinoNoirDebug));
  await page.locator('#toggleEditor').click();
  await page.locator('#deckNew').click();
  assert.equal(await page.locator('#deckCount').innerText(),'1');
  await page.locator('#deckName').fill('Aufgabendeck');
  await page.locator('#deckName').dispatchEvent('change');
  await page.locator('#deckAddCard').click();
  const card=page.locator('#deckCards .deck-card-row').first();
  await card.locator('textarea').fill('<img src=x onerror=alert(1)>');
  await card.locator('textarea').dispatchEvent('change');
  await card.locator('select[data-card-field="frequency"]').selectOption('multiple');
  await card.locator('input[data-card-field="copies"]').fill('3');
  await card.locator('input[data-card-field="copies"]').dispatchEvent('change');
  assert.match(await page.locator('#deckStats').innerText(),/3 \/ 3/);
  await page.locator('#deckCards button[data-card-action="icon"]').click();
  await page.locator('#customIconName').fill('favorite');
  await page.locator('#useCustomIcon').click();
  assert.match(await page.locator('#deckCards button[data-card-action="icon"]').innerText(),/favorite/);
  const originalId=await page.locator('#deckSelect').inputValue();
  await page.locator('#deckDuplicate').click();
  assert.equal(await page.locator('#deckCount').innerText(),'2');
  page.once('dialog',dialog=>dialog.accept());
  await page.locator('#deckDelete').click();
  await page.locator('#deckSelect').selectOption(originalId);
  for(let i=0;i<7;i++)await page.locator('#segmentList .segment-delete').last().click();
  await page.locator('#segmentList select[data-field="action"]').selectOption('deck');
  await page.locator('#segmentList select[data-field="deckId"]').selectOption(originalId);
  assert.equal(await page.locator('#segmentList select[data-field="deckId"]').inputValue(),originalId);
  await page.locator('#closeEditor').click();
  await page.locator('#spinHub').click();
  await page.waitForFunction(()=>window.__casinoNoirDebug.lastWinner===0&&!window.__casinoNoirDebug.isSpinning,{timeout:45000});
  await page.locator('#cardOverlay').waitFor({state:'visible',timeout:7000});
  assert.equal(await page.locator('#drawCard').isVisible(),true);
  assert.equal(await page.locator('#cardFront img').count(),0);
  await page.evaluate(()=>{document.getElementById('drawCard').click();document.getElementById('drawCard').click();});
  await page.locator('#nextRound').waitFor({state:'visible'});
  assert.equal(await page.locator('#cardFront .card-face-text').innerText(),'<img src=x onerror=alert(1)>');
  assert.equal(await page.locator('#cardFront img').count(),0,'untrusted text must stay text, not HTML');
  const cardIcon=await page.locator('#cardFront .card-face-icon').innerText();
  assert.ok(cardIcon&&cardIcon!=='favorite'&&cardIcon!=='favorite_border','card must show the symbol glyph, not its raw catalogue name');
  let remaining=await page.evaluate(()=>JSON.parse(localStorage.getItem('casino-noir-card-decks-v1')).decks[0].state.remaining);
  assert.deepEqual(Object.values(remaining),[2],'double click must consume exactly one copy');
  await page.reload();
  await page.waitForFunction(()=>Boolean(window.__casinoNoirDebug));
  await page.locator('#nextRound').waitFor({state:'visible',timeout:7000});
  remaining=await page.evaluate(()=>JSON.parse(localStorage.getItem('casino-noir-card-decks-v1')).decks[0].state.remaining);
  assert.deepEqual(Object.values(remaining),[2],'reload must not restore consumed copies');
  await page.locator('#nextRound').click();
  assert.equal(await page.locator('#cardOverlay').isVisible(),false);
  await page.locator('#toggleEditor').click();
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#exportJson').click();
  const download=await downloadPromise;
  assert.match(download.suggestedFilename(),/^casino-noir-/);
  await page.locator('#closeEditor').click();
  await page.setViewportSize({width:390,height:844});
  await page.locator('#toggleEditor').click();
  assert.ok(await page.locator('#deckHeading').isVisible());
  await page.locator('#closeEditor').click();

  const standalone=await context.newPage(),standaloneErrors=[];
  standalone.on('pageerror',e=>standaloneErrors.push(e.message));
  await standalone.route(/^https?:/,route=>route.abort());
  await standalone.goto(pathToFileURL(resolve('casino-noir-standalone.html')).href);
  await standalone.waitForFunction(()=>Boolean(window.__casinoNoirDebug));
  await standalone.locator('#toggleEditor').click();
  assert.ok(await standalone.locator('#deckHeading').isVisible());
  assert.deepEqual(standaloneErrors,[]);
  assert.deepEqual(errors,[]);
  console.log('PASS: editor, multiplicity, duplicate, segment binding, physical winner, card draw lock, XSS, refresh recovery, export, mobile, standalone.');
} finally {await browser.close();}
